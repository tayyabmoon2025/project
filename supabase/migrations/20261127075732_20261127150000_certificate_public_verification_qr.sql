/*
# Public certificate verification (QR code)

## 1. Purpose
Every printed certificate now carries a QR code. Scanning it opens a verification page
that confirms the certificate is genuine and shows the details the school office filed.

The verification page must work for whoever is holding the paper — a college clerk, an
employer, a board office — who has no account on this system. So this migration adds one
narrow, read-only door that returns the *verification* fields of a single certificate when
the scanner presents its number and code. It is deliberately not a general read of the
certificate register.

## 2. What is added

### New column on `school_student_certificates`
- `verification_code` (text, NOT NULL)
  A short six-character code (digits and capitals) generated by the database for every
  certificate. It is the second factor on the verification page: the certificate number
  alone is printed on the paper and is guessable, the code is not. A unique index keeps
  every code distinct.

### New function `public.verify_student_certificate(p_number text, p_code text)`
Returns a single JSON object, or `null` when nothing matches. It returns:
- `certificate_number`, `certificate_type`, `title`, `issued_on`
- `approval_status` (only `'released'` or `'pending'` — never the internal value)
- `student_name`, `admission_number`, `class_name`, `section_name`
- `school_name`, `verified_at`

It deliberately does NOT return the certificate body, the student's date of birth, the
guardian's name, contact numbers or the certificate's internal id.

Matching is exact and case-insensitive on both values, and the certificate must be
released by an administrator. A certificate still awaiting approval returns `null`, so a
held certificate cannot be confirmed from its paper copy.

### New function `public.regenerate_student_certificate_code(p_id uuid)`
Administrators only. Issues a fresh code for an existing certificate — used when a code
was printed in error and the paper was never handed out.

## 3. Back-fill
Existing certificates are given a code by the same generator, so a reprint of an old
certificate also carries a working QR code.

## 4. Security
- RLS on `school_student_certificates` is unchanged; the table itself is still not readable
  by the public. The verification data is reached only through the function below.
- `verify_student_certificate` is `SECURITY DEFINER`, has a fixed `search_path`, and is
  executable by `anon` and `authenticated` because the person scanning the paper is not
  signed in. It can only ever return the narrow field list above.
- `regenerate_student_certificate_code` is `SECURITY DEFINER`, checks `can_manage_users()`,
  and its EXECUTE is revoked from `PUBLIC` and `anon`.
- No table grants are widened.

## 5. Notes
1. The column default calls a helper function, so a direct INSERT that omits the column
   still receives a code.
2. The helper `certificate_verification_code()` is revoked from PUBLIC and anon: it is
   only ever called from inside the functions above.
3. Re-running this migration is safe — every object is created with IF NOT EXISTS or
   CREATE OR REPLACE, and the back-fill only touches rows whose code is empty.
*/

-- ---------------------------------------------------------------- the code itself

-- Six characters from an unambiguous alphabet: no O/0 or I/1 confusion when a code has to
-- be read off the paper or typed in by hand.
CREATE OR REPLACE FUNCTION public.certificate_verification_code()
RETURNS text
LANGUAGE plpgsql
VOLATILE
SET search_path TO 'public'
AS $function$
DECLARE
  v_alphabet constant text := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  v_code text := '';
  i int;
BEGIN
  FOR i IN 1..6 LOOP
    v_code := v_code || substr(v_alphabet, 1 + floor(random() * length(v_alphabet))::int, 1);
  END LOOP;
  RETURN v_code;
END;
$function$;

REVOKE ALL ON FUNCTION public.certificate_verification_code() FROM PUBLIC, anon;

-- ---------------------------------------------------------------- the column

ALTER TABLE public.school_student_certificates
  ADD COLUMN IF NOT EXISTS verification_code text;

-- Rows written before this column existed are given a code here.
UPDATE public.school_student_certificates
SET verification_code = public.certificate_verification_code()
WHERE verification_code IS NULL OR btrim(verification_code) = '';

ALTER TABLE public.school_student_certificates
  ALTER COLUMN verification_code SET DEFAULT public.certificate_verification_code();

-- A direct INSERT that omits the column gets the default; anything explicitly passed is
-- upper-cased so a code typed in lower case still matches.
CREATE OR REPLACE FUNCTION public.normalize_certificate_verification_code()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $function$
BEGIN
  IF NEW.verification_code IS NULL OR btrim(NEW.verification_code) = '' THEN
    NEW.verification_code := public.certificate_verification_code();
  ELSE
    NEW.verification_code := upper(btrim(NEW.verification_code));
  END IF;
  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION public.normalize_certificate_verification_code() FROM PUBLIC, anon;

DROP TRIGGER IF EXISTS trg_normalize_certificate_verification_code ON public.school_student_certificates;
CREATE TRIGGER trg_normalize_certificate_verification_code
BEFORE INSERT OR UPDATE ON public.school_student_certificates
FOR EACH ROW EXECUTE FUNCTION public.normalize_certificate_verification_code();

ALTER TABLE public.school_student_certificates
  ALTER COLUMN verification_code SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS school_student_certificates_verification_code_key
  ON public.school_student_certificates (verification_code);

-- ---------------------------------------------------------------- issue with a code

-- The issuing function is unchanged apart from writing the code explicitly, so the value
-- is returned to the issuing screen in the same row it already reads back.
DROP FUNCTION IF EXISTS public.admin_issue_student_certificate(uuid, text, text, text, text, text, date, text, text, text);

CREATE OR REPLACE FUNCTION public.admin_issue_student_certificate(
  p_student_id uuid,
  p_certificate_type text,
  p_title text,
  p_body text,
  p_slc_serial_number text DEFAULT NULL,
  p_certificate_number text DEFAULT NULL,
  p_issued_on date DEFAULT NULL,
  p_approval_status text DEFAULT 'pending',
  p_border_style text DEFAULT 'classic_gold_navy',
  p_font_style text DEFAULT 'classic_serif'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_row public.school_student_certificates;
  v_student public.school_students;
  v_type text := coalesce(nullif(btrim(p_certificate_type), ''), 'bonafide');
  v_issued_on date := coalesce(p_issued_on, CURRENT_DATE);
  v_number text := nullif(btrim(coalesce(p_certificate_number, '')), '');
  v_serial text := nullif(btrim(coalesce(p_slc_serial_number, '')), '');
  v_border text := nullif(btrim(coalesce(p_border_style, '')), '');
  v_font text := nullif(btrim(coalesce(p_font_style, '')), '');
  v_status text;
  v_prefix text;
  v_next int;
  v_code text;
BEGIN
  IF NOT public.can_manage_users() THEN
    RAISE EXCEPTION 'Only administrators can issue student certificates';
  END IF;

  SELECT * INTO v_student FROM public.school_students WHERE id = p_student_id;
  IF v_student.id IS NULL THEN
    RAISE EXCEPTION 'That student could not be found';
  END IF;

  IF v_type NOT IN (
    'school_leaving', 'transfer', 'birth_dob', 'character', 'bonafide',
    'fee_clearance', 'attempt', 'hope', 'provisional',
    'position_holder', 'merit', 'achievement', 'sports', 'cocurricular',
    'full_attendance'
  ) THEN
    RAISE EXCEPTION 'Choose a valid certificate type';
  END IF;

  IF p_body IS NULL OR btrim(p_body) = '' THEN
    RAISE EXCEPTION 'The certificate wording cannot be empty';
  END IF;

  -- An unknown border or font from a stale screen falls back to the default rather than
  -- failing the save: the wording is the important part, the frame is decoration.
  IF v_border IS NULL OR v_border NOT IN (
    'classic_gold_navy', 'official_slate', 'royal_emerald', 'modern_geometric', 'plain'
  ) THEN
    v_border := 'classic_gold_navy';
  END IF;

  IF v_font IS NULL OR v_font NOT IN (
    'classic_serif', 'elegant_playfair', 'modern_sans', 'formal_garamond'
  ) THEN
    v_font := 'classic_serif';
  END IF;

  -- A certificate is only ever released by an administrator, and this is where that is
  -- enforced: a release requested by anybody else is quietly stored as pending.
  v_status := CASE
    WHEN lower(btrim(coalesce(p_approval_status, 'pending'))) = 'approved'
      AND public.is_admin() THEN 'approved'
    ELSE 'pending'
  END;

  IF v_number IS NULL THEN
    PERFORM pg_advisory_xact_lock(hashtext('school_student_certificate_number'));
    v_prefix := CASE
      WHEN v_type IN ('school_leaving', 'transfer') THEN 'TUS-SLC-' || EXTRACT(YEAR FROM v_issued_on)::int::text || '-'
      WHEN v_type = 'birth_dob' THEN 'TUS-DOB-' || EXTRACT(YEAR FROM v_issued_on)::int::text || '-'
      ELSE 'TUS-CERT-' || EXTRACT(YEAR FROM v_issued_on)::int::text || '-'
    END;
    SELECT COALESCE(MAX((regexp_match(certificate_number, '([0-9]+)$'))[1]::int), 0) + 1
      INTO v_next
      FROM public.school_student_certificates
     WHERE certificate_number ~ ('^' || v_prefix || '[0-9]+$');
    v_number := v_prefix || lpad(v_next::text, 3, '0');
  END IF;

  -- The printed code is unique, so a clash is retried rather than failing the issue.
  LOOP
    v_code := public.certificate_verification_code();
    EXIT WHEN NOT EXISTS (
      SELECT 1 FROM public.school_student_certificates WHERE verification_code = v_code
    );
  END LOOP;

  INSERT INTO public.school_student_certificates
    (student_id, certificate_type, certificate_number, slc_serial_number, title, body,
     issued_on, approval_status, approved_by, approved_at, issued_by,
     border_style, font_style, verification_code)
  VALUES
    (p_student_id, v_type, v_number, v_serial, btrim(p_title), btrim(p_body),
     v_issued_on, v_status,
     CASE WHEN v_status = 'approved' THEN auth.uid() END,
     CASE WHEN v_status = 'approved' THEN now() END,
     auth.uid(),
     v_border, v_font, v_code)
  RETURNING * INTO v_row;

  -- The serial number written on a leaving certificate becomes the student's own serial
  -- number when they do not have one yet, so the profile and the certificate agree.
  IF v_serial IS NOT NULL
    AND v_type IN ('school_leaving', 'transfer')
    AND nullif(btrim(coalesce(v_student.slc_serial_number, '')), '') IS NULL THEN
    UPDATE public.school_students
       SET slc_serial_number = v_serial
     WHERE id = p_student_id;
  END IF;

  RETURN to_jsonb(v_row)
    || jsonb_build_object(
      'student_name', v_student.full_name,
      'admission_number', v_student.admission_number,
      'class_name', v_student.class_name,
      'section_name', v_student.section_name
    );
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_issue_student_certificate(uuid, text, text, text, text, text, date, text, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_issue_student_certificate(uuid, text, text, text, text, text, date, text, text, text) TO authenticated;

-- ---------------------------------------------------------------- verification door

CREATE OR REPLACE FUNCTION public.verify_student_certificate(p_number text, p_code text)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_row public.school_student_certificates;
  v_student public.school_students;
  v_profile public.school_institution_profile;
BEGIN
  SELECT * INTO v_row
    FROM public.school_student_certificates
   WHERE upper(btrim(certificate_number)) = upper(btrim(coalesce(p_number, '')))
     AND upper(btrim(coalesce(verification_code, ''))) = upper(btrim(coalesce(p_code, '')))
     AND approval_status = 'approved';

  IF v_row.id IS NULL THEN
    RETURN NULL;
  END IF;

  SELECT * INTO v_student FROM public.school_students WHERE id = v_row.student_id;
  SELECT * INTO v_profile FROM public.school_institution_profile WHERE id = 'default';

  RETURN jsonb_build_object(
    'certificate_number', v_row.certificate_number,
    'certificate_type', v_row.certificate_type,
    'title', v_row.title,
    'issued_on', v_row.issued_on,
    -- The internal status is never exposed: the page only needs to know the certificate
    -- is released, which is the only state that reaches this point anyway.
    'approval_status', 'released',
    'student_name', coalesce(v_student.full_name, 'Student'),
    'admission_number', v_student.admission_number,
    'class_name', v_student.class_name,
    'section_name', v_student.section_name,
    'school_name', coalesce(nullif(btrim(coalesce(v_profile.school_name, '')), ''), 'Ujala Public School'),
    'verified_at', now()
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.verify_student_certificate(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.verify_student_certificate(text, text) TO anon, authenticated;

-- ---------------------------------------------------------------- reissue a code

CREATE OR REPLACE FUNCTION public.regenerate_student_certificate_code(p_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_row public.school_student_certificates;
  v_code text;
BEGIN
  IF NOT public.can_manage_users() THEN
    RAISE EXCEPTION 'Only administrators can change a certificate code';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.school_student_certificates WHERE id = p_id) THEN
    RAISE EXCEPTION 'That certificate could not be found';
  END IF;

  LOOP
    v_code := public.certificate_verification_code();
    EXIT WHEN NOT EXISTS (
      SELECT 1 FROM public.school_student_certificates WHERE verification_code = v_code
    );
  END LOOP;

  UPDATE public.school_student_certificates
     SET verification_code = v_code
   WHERE id = p_id
  RETURNING * INTO v_row;

  RETURN to_jsonb(v_row);
END;
$function$;

REVOKE ALL ON FUNCTION public.regenerate_student_certificate_code(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.regenerate_student_certificate_code(uuid) TO authenticated;
